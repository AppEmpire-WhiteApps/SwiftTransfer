import SwiftUI

/// Empty chat: illustration, greeting, AI disclaimer and quick-question chips.
struct AssistantWelcomeView: View {
    var onQuestion: (String) -> Void

    static let quickQuestions: [LocalizedStringResource] = [
        "How do I move photos to Android?",
        "Why can't the second phone be found?",
        "What can't be moved from iPhone?",
        "How do I move WhatsApp?",
        "How do I transfer by cable?",
        "How do I import contacts on Android?",
    ]

    var body: some View {
        VStack(spacing: Spacing.xl) {
            IllustrationView(illustration: .assistantEmpty, height: 170, floating: true)

            VStack(spacing: Spacing.s) {
                Text("Hi! I'm your transfer assistant")
                    .font(AppFont.title2)
                    .foregroundStyle(AppColor.textPrimary)
                    .accessibilityAddTraits(.isHeader)
                Text("Ask about moving contacts, photos and other data between iPhone and Android, or using an external drive.")
                    .font(AppFont.callout)
                    .foregroundStyle(AppColor.textSecondary)
            }
            .multilineTextAlignment(.center)
            .fixedSize(horizontal: false, vertical: true)

            AssistantDisclaimer()

            VStack(alignment: .leading, spacing: Spacing.m) {
                Text("Popular questions")
                    .font(AppFont.headline)
                    .foregroundStyle(AppColor.textPrimary)
                    .accessibilityAddTraits(.isHeader)
                AssistantFlowLayout {
                    ForEach(Self.quickQuestions.indices, id: \.self) { index in
                        let question = Self.quickQuestions[index]
                        Button {
                            onQuestion(String(localized: question))
                        } label: {
                            Chip(title: Text(question), systemImage: "sparkles")
                        }
                        .buttonStyle(.plain)
                        .accessibilityHint(Text("Sends this question to the assistant"))
                    }
                }
            }
            .frame(maxWidth: .infinity, alignment: .leading)
            .cardStyle()
        }
        .frame(maxWidth: .infinity)
        .padding(.vertical, Spacing.l)
    }
}

/// "Answers are generated by AI" note.
struct AssistantDisclaimer: View {
    var body: some View {
        Label {
            Text("Answers are generated by AI and may contain inaccuracies")
                .fixedSize(horizontal: false, vertical: true)
        } icon: {
            Image(systemName: "info.circle")
        }
        .font(AppFont.footnote)
        .foregroundStyle(AppColor.textTertiary)
        .multilineTextAlignment(.leading)
    }
}

/// Shown when the build has no LLMApps key: the rest of the app keeps working.
struct AssistantUnavailableView: View {
    var onOpenGuides: (() -> Void)?

    var body: some View {
        ScrollView {
            EmptyStateView(
                illustration: .assistantEmpty,
                title: "The assistant will be available soon",
                message: "Meanwhile, the step-by-step guides and the connection check help with any transfer.",
                actionTitle: onOpenGuides == nil ? nil : "Open guides",
                action: onOpenGuides
            )
            .frame(maxWidth: 560)
            .frame(maxWidth: .infinity)
            .padding(.top, Spacing.xxxl)
            .pageMargins()
        }
        .screenBackground()
    }
}

#Preview("Welcome") {
    ScrollView {
        AssistantWelcomeView { _ in }
            .pageMargins()
    }
    .screenBackground()
}

#Preview("Unavailable") {
    AssistantUnavailableView {}
}
